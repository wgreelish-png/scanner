import Foundation

/// Dollar amounts preserve fractional-cent lot costs until a final sale floor is rounded up.
struct TagProfitInputs: Codable, Equatable, Sendable {
    var acquisitionCost: Decimal?
    var allocatedExpenses: Decimal
    var minimumDesiredProfit: Decimal?
    var fixedPaymentFee: Decimal
    /// A fraction: 0.029 represents a 2.9% payment fee.
    var percentagePaymentFee: Decimal

    init(acquisitionCost: Decimal?, allocatedExpenses: Decimal = 0,
         minimumDesiredProfit: Decimal? = nil, fixedPaymentFee: Decimal = 0,
         percentagePaymentFee: Decimal = 0) {
        self.acquisitionCost = acquisitionCost
        self.allocatedExpenses = allocatedExpenses
        self.minimumDesiredProfit = minimumDesiredProfit
        self.fixedPaymentFee = fixedPaymentFee
        self.percentagePaymentFee = percentagePaymentFee
    }
}

enum StickerPrice: Codable, Equatable, Sendable {
    /// The value is cents and is always a whole dollar when generated by TagPricing.
    case individual(Int64)
    case twoForOne

    var integerPriceCents: Int64? {
        if case let .individual(cents) = self { return cents }
        return nil
    }

    var displayText: String {
        switch self {
        case let .individual(cents): return "$\(cents / 100)"
        case .twoForOne: return "2 for $1"
        }
    }
}

enum TagPricingReason: String, Codable, Equatable, Sendable {
    case missingMarket, invalidMarket, unknownAcquisitionCost, missingMinimumDesiredProfit
    case invalidAcquisitionCost, invalidAllocatedExpenses, invalidMinimumDesiredProfit
    case invalidFixedPaymentFee, invalidPercentagePaymentFee, invalidActualPrice
    case amountOutOfRange, belowBreakEven, belowPreferredProfit, invalidDiscountPolicy
    case bulkRequiresBundleReview

    var message: String {
        switch self {
        case .missingMarket: return "Market price is unknown. Review the tag manually."
        case .invalidMarket: return "Market price must be a valid nonnegative dollar amount within the supported range."
        case .unknownAcquisitionCost: return "Actual acquisition cost is unknown; profit cannot be verified."
        case .missingMinimumDesiredProfit: return "Set your minimum desired profit before using a suggested offer."
        case .invalidAcquisitionCost: return "Actual acquisition cost is invalid."
        case .invalidAllocatedExpenses: return "Allocated expenses must be valid nonnegative dollar amounts."
        case .invalidMinimumDesiredProfit: return "Minimum desired profit must be a valid nonnegative dollar amount."
        case .invalidFixedPaymentFee: return "The fixed payment fee must be a valid nonnegative dollar amount."
        case .invalidPercentagePaymentFee: return "The payment fee must be a fraction from zero up to, but excluding, one."
        case .invalidActualPrice: return "The selected price is outside the supported cents range."
        case .amountOutOfRange: return "The calculated price exceeds the supported range."
        case .belowBreakEven: return "This price is below the break-even floor after costs and fees."
        case .belowPreferredProfit: return "This price does not meet your minimum desired profit after costs and fees."
        case .invalidDiscountPolicy: return "Suggested discount percentages must stay within their configured tag tiers."
        case .bulkRequiresBundleReview: return "Check the selected 2 for $1 cards together so the payment fee is counted once."
        }
    }
}

enum TagPricingFailure: Error, Equatable, Sendable {
    case invalidInputs([TagPricingReason])
    case amountOutOfRange
}

/// Fractions, with no default profit amount. Discount choices are constrained to the requested tiers.
struct TagDiscountPolicy: Codable, Equatable, Sendable {
    var underFive: Decimal = Decimal(25) / 1_000
    var fiveToTwenty: Decimal = Decimal(5) / 100
    var twentyToHundred: Decimal = Decimal(65) / 1_000
    var hundredAndAbove: Decimal = Decimal(75) / 1_000

    var isValid: Bool {
        valid(underFive, from: 0, through: Decimal(5) / 100)
            && valid(fiveToTwenty, from: Decimal(5) / 100, through: Decimal(5) / 100)
            && valid(twentyToHundred, from: Decimal(5) / 100, through: Decimal(8) / 100)
            && valid(hundredAndAbove, from: Decimal(5) / 100, through: Decimal(10) / 100)
    }

    private func valid(_ value: Decimal, from lower: Decimal, through upper: Decimal) -> Bool {
        !value.isNaN && value >= lower && value <= upper
    }
}

struct TagPriceEvaluation: Equatable, Sendable {
    var tag: StickerPrice?
    var breakEvenCents: Int64?
    var preferredFloorCents: Int64?
    var suggestedOfferCents: Int64?
    var reasons: [TagPricingReason]
    var requiresManualReview: Bool { !reasons.isEmpty }
}

enum TagPricing {
    static let maximumCents: Int64 = 99_999_999_999
    static let maximumDollars = Decimal(maximumCents) / 100

    static func evaluate(market: Decimal?, inputs: TagProfitInputs,
                         discounts: TagDiscountPolicy = TagDiscountPolicy()) -> TagPriceEvaluation {
        var result = TagPriceEvaluation(tag: nil, breakEvenCents: nil, preferredFloorCents: nil,
                                        suggestedOfferCents: nil, reasons: validateInputs(inputs))
        if let market {
            if validAmount(market) {
                if market < Decimal(75) / 100 { result.tag = .twoForOne }
                else if market < 1 { result.tag = .individual(100) }
                else {
                    let increment: Decimal = market < 100 ? 1 : 5
                    let dollars = rounded(market / increment, mode: .down) * increment
                    result.tag = .individual(NSDecimalNumber(decimal: dollars * 100).int64Value)
                }
            } else { append(.invalidMarket, to: &result.reasons) }
        } else { append(.missingMarket, to: &result.reasons) }

        do { result.breakEvenCents = try floorCents(inputs: inputs, desiredProfit: 0) }
        catch { appendFloorFailure(error, to: &result.reasons) }
        if let desired = inputs.minimumDesiredProfit {
            do { result.preferredFloorCents = try floorCents(inputs: inputs, desiredProfit: desired) }
            catch { appendFloorFailure(error, to: &result.reasons) }
        }
        if !discounts.isValid { append(.invalidDiscountPolicy, to: &result.reasons) }

        if let price = result.tag?.integerPriceCents {
            if let floor = result.breakEvenCents, price < floor { append(.belowBreakEven, to: &result.reasons) }
            if let floor = result.preferredFloorCents, price < floor { append(.belowPreferredProfit, to: &result.reasons) }
            if result.reasons.isEmpty, let floor = result.preferredFloorCents {
                result.suggestedOfferCents = suggestedOfferCents(stickerCents: price,
                                                                 preferredFloorCents: floor, discounts: discounts)
            }
        } else if result.tag == .twoForOne {
            append(.bulkRequiresBundleReview, to: &result.reasons)
        }
        return result
    }

    /// Missing costs/profit settings stay distinct from invalid numeric input.
    static func validateInputs(_ inputs: TagProfitInputs) -> [TagPricingReason] {
        var reasons: [TagPricingReason] = []
        if let cost = inputs.acquisitionCost {
            if !validAmount(cost) { reasons.append(.invalidAcquisitionCost) }
        } else { reasons.append(.unknownAcquisitionCost) }
        if !validAmount(inputs.allocatedExpenses) { reasons.append(.invalidAllocatedExpenses) }
        if let desired = inputs.minimumDesiredProfit {
            if !validAmount(desired) { reasons.append(.invalidMinimumDesiredProfit) }
        } else { reasons.append(.missingMinimumDesiredProfit) }
        if !validAmount(inputs.fixedPaymentFee) { reasons.append(.invalidFixedPaymentFee) }
        if inputs.percentagePaymentFee.isNaN || inputs.percentagePaymentFee < 0 || inputs.percentagePaymentFee >= 1 {
            reasons.append(.invalidPercentagePaymentFee)
        }
        return reasons
    }

    /// Minimum gross cents covering cost, expenses, desired profit, and payment fees.
    /// The ceiling, including fractional-cent acquisition cost, prevents rounding away a loss.
    static func floorCents(inputs: TagProfitInputs, desiredProfit: Decimal) throws -> Int64? {
        let invalid = validateInputs(inputs).filter {
            $0 != .unknownAcquisitionCost && $0 != .missingMinimumDesiredProfit && $0 != .invalidMinimumDesiredProfit
        }
        var problems = invalid
        if !validAmount(desiredProfit) { problems.append(.invalidMinimumDesiredProfit) }
        guard problems.isEmpty else { throw TagPricingFailure.invalidInputs(problems) }
        guard let cost = inputs.acquisitionCost else { return nil }
        let required = cost + inputs.allocatedExpenses + desiredProfit + inputs.fixedPaymentFee
        let retainedFraction = 1 - inputs.percentagePaymentFee
        let rawCents = required * 100 / retainedFraction
        guard !rawCents.isNaN, rawCents >= 0 else { throw TagPricingFailure.amountOutOfRange }
        let ceiling = rounded(rawCents, mode: .up)
        guard ceiling <= Decimal(maximumCents) else { throw TagPricingFailure.amountOutOfRange }
        var cents = NSDecimalNumber(decimal: ceiling).int64Value
        // Decimal division may round at its precision limit; verify the resulting amount covers costs.
        if Decimal(cents) / 100 * retainedFraction < required {
            guard cents < maximumCents else { throw TagPricingFailure.amountOutOfRange }
            cents += 1
        }
        return cents
    }

    /// Used for a manual price override as well as a generated offer. Warnings do not change the price.
    static func validateActualPriceCents(_ priceCents: Int64, inputs: TagProfitInputs) -> [TagPricingReason] {
        var reasons = validateInputs(inputs)
        guard (0...maximumCents).contains(priceCents) else {
            append(.invalidActualPrice, to: &reasons)
            return reasons
        }
        do {
            if let floor = try floorCents(inputs: inputs, desiredProfit: 0), priceCents < floor {
                append(.belowBreakEven, to: &reasons)
            }
        } catch { appendFloorFailure(error, to: &reasons) }
        if let desired = inputs.minimumDesiredProfit {
            do {
                if let floor = try floorCents(inputs: inputs, desiredProfit: desired), priceCents < floor {
                    append(.belowPreferredProfit, to: &reasons)
                }
            } catch { appendFloorFailure(error, to: &reasons) }
        }
        return reasons
    }

    static func suggestedOfferCents(stickerCents: Int64, preferredFloorCents: Int64,
                                    discounts: TagDiscountPolicy = TagDiscountPolicy()) -> Int64? {
        guard discounts.isValid, (0...maximumCents).contains(stickerCents), preferredFloorCents >= 0,
              preferredFloorCents <= stickerCents else { return nil }
        let target: Decimal, minimumDiscount: Decimal, maximumDiscount: Decimal, increment: Int64
        switch stickerCents {
        case ..<500:
            target = discounts.underFive; minimumDiscount = 0; maximumDiscount = Decimal(5) / 100; increment = 25
        case ..<2_000:
            target = discounts.fiveToTwenty; minimumDiscount = Decimal(5) / 100
            maximumDiscount = Decimal(5) / 100; increment = 50
        case ..<10_000:
            target = discounts.twentyToHundred; minimumDiscount = Decimal(5) / 100
            maximumDiscount = Decimal(8) / 100; increment = 100
        default:
            target = discounts.hundredAndAbove; minimumDiscount = Decimal(5) / 100
            maximumDiscount = Decimal(10) / 100; increment = 500
        }
        let price = Decimal(stickerCents)
        let lower = max(preferredFloorCents, integer(price * (1 - maximumDiscount), mode: .up))
        let upper = min(stickerCents, integer(price * (1 - minimumDiscount), mode: .down))
        // Keeping the sticker is preferable to a discount that violates the selected profit floor.
        guard lower <= upper else { return stickerCents }
        let targetCents = min(upper, max(lower, integer(price * (1 - target), mode: .plain)))
        let convenient = integer(Decimal(targetCents) / Decimal(increment), mode: .plain) * increment
        if (lower...upper).contains(convenient) { return convenient }
        return targetCents
    }

    private static func validAmount(_ value: Decimal) -> Bool {
        !value.isNaN && value >= 0 && value <= maximumDollars
    }

    private static func rounded(_ value: Decimal, mode: Decimal.RoundingMode) -> Decimal {
        var source = value, result = Decimal.zero
        NSDecimalRound(&result, &source, 0, mode)
        return result
    }

    private static func integer(_ value: Decimal, mode: Decimal.RoundingMode) -> Int64 {
        NSDecimalNumber(decimal: rounded(value, mode: mode)).int64Value
    }

    private static func append(_ reason: TagPricingReason, to reasons: inout [TagPricingReason]) {
        if !reasons.contains(reason) { reasons.append(reason) }
    }

    private static func appendFloorFailure(_ error: Error, to reasons: inout [TagPricingReason]) {
        if case let TagPricingFailure.invalidInputs(invalid) = error {
            for reason in invalid { append(reason, to: &reasons) }
        } else { append(.amountOutOfRange, to: &reasons) }
    }
}
